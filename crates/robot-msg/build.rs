// 掉 pedantic / nursery 噪音（例如 "function too long" / "unnecessary Debug in
// panic args"），保留 clippy::all 的真错误覆盖。
#![allow(clippy::pedantic, clippy::nursery)]

//! robot-msg · build.rs
//!
//! ## 工作流
//!
//! 1. 判断 host 平台，定位 vendor flatc（`3rd-party/flatc/<host>/flatc`）。
//! 2. 调 flatc `--rust --rust-module-root-file` 生成到 `$OUT_DIR/gen/`：
//!    - 每个 type 一个 `robot/msg/<snake_case_name>_generated.rs`
//!    - v0 快照到 `robot/msg/v_0/joint_state_generated.rs`
//! 3. flatc 自带的 `mod.rs` 只会挂最后一个 `.fbs` 的 tables（25.12.19 的表现），
//!    本脚本**自己重写** `$OUT_DIR/gen_root.rs`，扫描目录把所有 `*_generated.rs`
//!    用 `#[path = "…"]` 挂入正确的 `pub mod robot { pub mod msg { ... } }`
//!    结构；lib.rs 只 `include!` 这一个入口。
//! 4. 发出 `cargo:rerun-if-changed` 让 schema / flatc 变化触发重生成。
//!
//! ## 平台
//!
//! - `macos + aarch64`  → `darwin-arm64/flatc`
//! - `linux + x86_64`   → `linux-x86_64/flatc`
//! - `linux + aarch64`  → `linux-aarch64/flatc`（需手动从源码编译填充，见 README）
//! - 其他 → panic；Windows 不支持（Step 2 退出标准：Linux/macOS 无网可 build）

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let repo_root = manifest_dir
        .parent()
        .and_then(Path::parent)
        .expect("expected crates/robot-msg to live under <repo>/crates");

    let platform = host_platform();
    let flatc = repo_root
        .join("3rd-party")
        .join("flatc")
        .join(platform)
        .join("flatc");

    assert!(
        flatc.exists(),
        "vendor flatc not found at {:?}. run `bash scripts/refresh_flatc.sh` \
         or see 3rd-party/flatc/README.md (linux-aarch64 需手动从源码编译)",
        flatc
    );

    let schemas_dir = manifest_dir.join("schemas");
    let old_dir = schemas_dir.join("old");

    let current_schemas: [&str; 14] = [
        "blob.fbs",
        "frame_header.fbs",
        "joint.fbs",
        "twist.fbs",
        "image.fbs",
        "pointcloud.fbs",
        "tensor.fbs",
        "event.fbs",
        "clear_estop.fbs",
        "action_status.fbs",
        "action_request.fbs",
        "action_event.fbs",
        "scripted_payload.fbs",
        "ik_payload.fbs",
    ];
    let v0_schemas: [&str; 1] = ["joint_v0.fbs"];

    // --- 2. flatc 生成 ---------------------------------------------------
    let gen_dir = out_dir.join("gen");
    // 每次 clean slate，避免旧 schema 残留造成 gen_root 多挂。
    if gen_dir.exists() {
        fs::remove_dir_all(&gen_dir).expect("remove stale gen dir");
    }
    fs::create_dir_all(&gen_dir).expect("create gen dir");

    let mut cmd = Command::new(&flatc);
    cmd.arg("--rust")
        .arg("--rust-module-root-file")
        .arg("-o")
        .arg(&gen_dir)
        .arg("-I")
        .arg(&schemas_dir);
    for s in current_schemas {
        cmd.arg(schemas_dir.join(s));
    }
    for s in v0_schemas {
        cmd.arg(old_dir.join(s));
    }

    let status = cmd
        .status()
        .unwrap_or_else(|e| panic!("failed to spawn flatc {flatc:?}: {e}"));
    assert!(
        status.success(),
        "flatc generation failed (exit status {status:?}); cmd: {cmd:?}"
    );

    // --- 3. 自己写 gen_root.rs ------------------------------------------
    //
    // flatc 自带的 mod.rs 不完整（25.12.19 只挂最后一个 schema 的 tables），
    // 本脚本扫描 gen_dir/robot/msg/ 与 gen_dir/robot/msg/v_0/ 下的实际产物，
    // 生成覆盖全部类型的入口。
    let msg_dir = gen_dir.join("robot").join("msg");
    let v0_dir = msg_dir.join("v_0");
    assert!(
        msg_dir.is_dir(),
        "expected flatc to create {:?}; got none",
        msg_dir
    );

    let current_mods = list_generated_mods(&msg_dir);
    assert!(
        !current_mods.is_empty(),
        "no *_generated.rs produced under {:?}",
        msg_dir
    );
    let v0_mods = if v0_dir.is_dir() {
        list_generated_mods(&v0_dir)
    } else {
        Vec::new()
    };

    let gen_root = out_dir.join("gen_root.rs");
    let mut src = String::new();
    src.push_str("// generated by robot-msg/build.rs — do not edit\n");
    src.push_str("pub mod robot {\n");
    src.push_str("    use super::*;\n");
    src.push_str("    pub mod msg {\n");
    src.push_str("        use super::*;\n");
    for module in &current_mods {
        let path = msg_dir.join(format!("{module}.rs"));
        src.push_str(&format!(
            "        #[path = {path:?}]\n        mod {module};\n        pub use self::{module}::*;\n",
            path = path.display().to_string(),
        ));
    }
    if !v0_mods.is_empty() {
        // v_0 只有单个 schema（JointState）时，常规的 `pub use
        // self::joint_state_generated::*;` 与 generated 文件自身的
        // `use super::*` 会在 nightly 下触发 ambiguous-glob-reexport hard
        // error。这里只声明 `pub mod <type>_generated`（不做 glob），由
        // lib.rs 把该 mod 以别名 re-export 成 `v0`。
        src.push_str("        pub mod v_0 {\n");
        for module in &v0_mods {
            let path = v0_dir.join(format!("{module}.rs"));
            src.push_str(&format!(
                "            #[path = {path:?}]\n            pub mod {module};\n",
                path = path.display().to_string(),
            ));
        }
        src.push_str("        } // v_0\n");
    }
    src.push_str("    } // msg\n");
    src.push_str("} // robot\n");
    fs::write(&gen_root, src).expect("write gen_root.rs");

    // --- 4. rerun triggers ---------------------------------------------
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", flatc.display());
    for s in current_schemas {
        println!("cargo:rerun-if-changed={}", schemas_dir.join(s).display());
    }
    for s in v0_schemas {
        println!("cargo:rerun-if-changed={}", old_dir.join(s).display());
    }
}

fn host_platform() -> &'static str {
    let os = env::consts::OS;
    let arch = env::consts::ARCH;
    match (os, arch) {
        ("macos", "aarch64") => "darwin-arm64",
        ("linux", "x86_64") => "linux-x86_64",
        ("linux", "aarch64") => "linux-aarch64",
        _ => panic!(
            "robot-msg build.rs: unsupported host platform {os}/{arch}. \
             Only macOS arm64 / Linux x86_64 / Linux aarch64 are vendored; \
             see 3rd-party/flatc/README.md."
        ),
    }
}

/// 扫描目录列出 `*_generated.rs` 的裸文件名（不含扩展名）。
fn list_generated_mods(dir: &Path) -> Vec<String> {
    let mut names: Vec<String> = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("read_dir({dir:?}): {e}"))
        .filter_map(Result::ok)
        .filter_map(|e| {
            let p = e.path();
            if p.is_file() && p.extension().and_then(|s| s.to_str()) == Some("rs") {
                p.file_stem()
                    .and_then(|s| s.to_str())
                    .filter(|s| s.ends_with("_generated"))
                    .map(str::to_owned)
            } else {
                None
            }
        })
        .collect();
    names.sort();
    names
}
